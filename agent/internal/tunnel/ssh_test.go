// memSSHServer is an in-test SSH server (a loopback inside the x/crypto library, no real sshd):
// an in-memory ed25519 host key + publickey authentication (checking only the username and key shape) +
// direct-tcpip channels forwarded to a local echo. The handshake count feeds the connection-reuse assertion.
type memSSHServer struct {
	hs atomic.Int32
	// hostKeyLine is the known_hosts line of this server's host key (used for client-side verification).
	hostKeyLine string

	ln net.Listener
	wg sync.WaitGroup
}

func newEcho(t *testing.T) string {
	t.Helper()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = ln.Close() })
	go func() {
		for {
			c, err := ln.Accept()
			if err != nil {
				return
			}
			go func() { _, _ = io.Copy(c, c); _ = c.Close() }()
		}
	}()
	return ln.Addr().String()
}

func startMemSSH(t *testing.T, echoAddr string) *memSSHServer {
	t.Helper()
	_, hostPriv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	hostSigner, err := ssh.NewSignerFromKey(hostPriv)
	if err != nil {
		t.Fatal(err)
	}
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	s := &memSSHServer{ln: ln, hostKeyLine: ""}
	cfg := &ssh.ServerConfig{
		// publickey authentication (matching the production single form): the test checks only the username, and the key shape
		// is enough to pass -- the client key is generated by the test, with no fingerprint database to compare against.
		PublicKeyCallback: func(meta ssh.ConnMetadata, key ssh.PublicKey) (*ssh.Permissions, error) {
			if meta.User() != "ferry" {
				return nil, fmt.Errorf("user %q not allowed", meta.User())
			}
			return &ssh.Permissions{}, nil
		},
	}
	cfg.AddHostKey(hostSigner)
	s.hostKeyLine = knownhosts.Line([]string{"[" + ln.Addr().String() + "]"}, hostSigner.PublicKey())
	s.wg.Add(1)
	go func() {
		defer s.wg.Done()
		for {
			c, err := ln.Accept()
			if err != nil {
				return
			}
			s.hs.Add(1)
			conn, chans, reqs, err := ssh.NewServerConn(c, cfg)
			if err != nil {
				continue
			}
			s.wg.Add(1)
			go func() {
				defer s.wg.Done()
				_ = conn.Wait()
			}()
			go s.serve(chans, reqs, echoAddr)
		}
	}()
	t.Cleanup(func() {
		_ = ln.Close()
		s.wg.Wait()
	})
	return s
}

// serve handles a direct-tcpip channel (the sshd forwarding semantics): after Accept it dials the echo
// and copies both ways.
func (s *memSSHServer) serve(chans <-chan ssh.NewChannel, reqs <-chan *ssh.Request, echoAddr string) {
	go func() {
		for req := range reqs {
			if req.WantReply {
				_ = req.Reply(false, nil)
			}
		}
	}()
	for newCh := range chans {
		if newCh.ChannelType() != "direct-tcpip" {
			_ = newCh.Reject(ssh.UnknownChannelType, "unsupported")
			continue
		}
		ch, _, err := newCh.Accept()
		if err != nil {
			continue
		}
		up, err := net.Dial("tcp", echoAddr)
		if err != nil {
			_ = ch.Close()
			continue
		}
		go func() {
			defer func() { _ = ch.Close(); _ = up.Close() }()
			done := make(chan struct{}, 2)
			go func() { _, _ = io.Copy(up, ch); done <- struct{}{} }()
			go func() { _, _ = io.Copy(ch, up); done <- struct{}{} }()
			<-done
			<-done
		}()
	}
}

// sshdAddr takes the server's host:port (needed to generate the host key line).
func (s *memSSHServer) sshdAddr() string { return s.ln.Addr().String() }

// writeClientKey generates an RSA private key PEM (PKCS1, parseable by ssh.ParsePrivateKey).
func writeClientKey(t *testing.T, dir string) string {
	t.Helper()
	key, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "id_rsa")
	pemBytes := pem.EncodeToMemory(&pem.Block{Type: "RSA PRIVATE KEY", Bytes: x509.MarshalPKCS1PrivateKey(key)})
	if err := os.WriteFile(path, pemBytes, 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

// newSSHTunnel builds the ssh plugin with fully configured Options; an empty knownHostsLine means no known_hosts.
func newSSHTunnel(t *testing.T, sshdAddr, echoAddr, knownHostsLine string) Tunnel {
	t.Helper()
	dir := t.TempDir()
	opts := Options{
		ServerName:     sshdAddr,
		AuthUser:       "ferry",
		KeyFile:        writeClientKey(t, dir),
		KnownHostsFile: "",
		ForwardAddr:    echoAddr,
		Timeout:        5 * time.Second,
	}
	if knownHostsLine != "" {
		khPath := filepath.Join(dir, "known_hosts")
		if err := os.WriteFile(khPath, []byte(knownHostsLine+"\n"), 0o600); err != nil {
			t.Fatal(err)
		}
		opts.KnownHostsFile = khPath
	}
	tn, err := Open("ssh", opts)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = tn.Close() })
	return tn
}

// roundtrip sends one echo round trip through the plugin's Dial.
func roundtrip(t *testing.T, tn Tunnel) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	conn, err := tn.Dial(ctx, "ignored-by-ssh")
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close()
	msg := "ping-ferry"
	if _, err := conn.Write([]byte(msg)); err != nil {
		t.Fatal(err)
	}
	buf := make([]byte, len(msg))
	if _, err := io.ReadFull(conn, buf); err != nil {
		t.Fatal(err)
	}
	if string(buf) != msg {
		t.Fatalf("roundtrip got %q want %q", buf, msg)
	}
}

// TestSSHTunnelEndToEnd covers the full loopback: Dial -> direct-tcpip -> echo; two frontend connections
// reuse the same SSH connection (exactly one handshake); a mismatched auth user is rejected.
func TestSSHTunnelEndToEnd(t *testing.T) {
	echo := newEcho(t)
	srv := startMemSSH(t, echo)
	tn := newSSHTunnel(t, srv.sshdAddr(), echo, "")
	roundtrip(t, tn)
	roundtrip(t, tn)
	if n := srv.hs.Load(); n != 1 {
		t.Fatalf("ssh handshakes = %d, want 1 (client reuse)", n)
	}
	// the net.Conn adapter surface: the ssh tunnel connection's address methods work (relay accounting needs them).
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	conn, err := tn.Dial(ctx, "ignored")
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close()
	if conn.LocalAddr() == nil || conn.RemoteAddr() == nil {
		t.Fatal("ssh conn must expose net.Addr (relay accounting uses it)")
	}
	// the deadline limitation is asserted as it is: x/crypto channel connections do not support it (the error may be ignored,
	// PingPong ignores it the same way, and timeouts rely on the application-layer 3-miss verdict as the backstop) --
	// it is enough that the write/read round trip still works after the deadline calls.
	_ = conn.SetDeadline(time.Now().Add(time.Second))
	roundtripOnce(t, conn)
}

// roundtripOnce sends one round trip over an already-established connection.
func roundtripOnce(t *testing.T, conn net.Conn) {
	t.Helper()
	msg := "pong-ferry"
	if _, err := conn.Write([]byte(msg)); err != nil {
		t.Fatal(err)
	}
	buf := make([]byte, len(msg))
	if _, err := io.ReadFull(conn, buf); err != nil {
		t.Fatal(err)
	}
	if string(buf) != msg {
		t.Fatalf("roundtrip got %q want %q", buf, msg)
	}
}

// TestSSHTunnelHostKeyVerify covers a matching known_hosts -> pass, a mismatch -> reject (the host key
// verification leg; the production rule: known_hosts is mandatory).
func TestSSHTunnelHostKeyVerify(t *testing.T) {
	echo := newEcho(t)
	srv := startMemSSH(t, echo)

	// the server's host key is unknown (known_hosts holds a different key's line): rejected.
	wrongSigner, err := ssh.NewSignerFromKey(func() ed25519.PrivateKey {
		_, priv, _ := ed25519.GenerateKey(rand.Reader)
		return priv
	}())
	if err != nil {
		t.Fatal(err)
	}
	wrongLine := knownhosts.Line([]string{"[" + srv.sshdAddr() + "]"}, wrongSigner.PublicKey())
	tn := newSSHTunnel(t, srv.sshdAddr(), echo, wrongLine)
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	if _, err := tn.Dial(ctx, "ignored"); err == nil {
		t.Fatal("unknown host key must be rejected")
	}

	// the server's real host key line: passes.
	tn2 := newSSHTunnel(t, srv.sshdAddr(), echo, srv.hostKeyLine)
	roundtrip(t, tn2)
}

// TestSSHTunnelMissingFields covers missing config fields being rejected: the sshd address/user/private key/forward target
// are four required pieces; without any of them it does not pose as dialable (validation lives in the plugin factory).
func TestSSHTunnelMissingFields(t *testing.T) {
	dir := t.TempDir()
	key := writeClientKey(t, dir)
	base := Options{ServerName: "127.0.0.1:22", AuthUser: "ferry", KeyFile: key,
		ForwardAddr: "127.0.0.1:10800", Timeout: time.Second}
	tn, err := Open("ssh", base)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = tn.Close() })
	ctx := context.Background()

	// emptying any field one by one is rejected.
	for _, mutate := range []func(*Options){
		func(o *Options) { o.ServerName = "" },
		func(o *Options) { o.AuthUser = "" },
		func(o *Options) { o.KeyFile = "" },
		func(o *Options) { o.ForwardAddr = "" },
	} {
		o := base
		mutate(&o)
		plug, err := Open("ssh", o)
		if err != nil {
			t.Fatalf("Open with %+v: %v", o, err)
		}
		if _, err := plug.Dial(ctx, "x"); err == nil {
			t.Fatalf("Dial with %+v must fail (missing config)", o)
		}
	}
	// a missing key file is rejected.
	o := base
	o.KeyFile = filepath.Join(dir, "missing")
	plug, err := Open("ssh", o)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := plug.Dial(ctx, "x"); err == nil {
		t.Fatal("missing key file must fail")
	}
}

// TestSSHRegistered covers the ssh plugin being registered while the default plugin is unaffected (an alternative never steals the default).
func TestSSHRegistered(t *testing.T) {
	if DefaultPlugin != "tls-camo" {
		t.Fatalf("default plugin = %s, want tls-camo (ssh is fallback only)", DefaultPlugin)
	}
	found := false
	for _, n := range Names() {
		if n == "ssh" {
			found = true
		}
	}
	if !found {
		t.Fatal("ssh plugin not registered")
	}
}
