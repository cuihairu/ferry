// Package payment defines the collection Provider contract and registry, shared by
// the server and the payments/ plugins; card keys (card) go first with zero
// credentials, and epusdt/Wechat/Alipay are wired in per phase (see "Payment Design" §1).
package payment

import (
	"context"
	"fmt"
	"sort"
	"sync"
	"time"
)

// Provider is the contract for one collection channel.
type Provider interface {
	Name() string
	// CreateOrder creates a collection order, returning the external receipt ID and the redirect URL (empty for card-key channels).
	CreateOrder(ctx context.Context, o Order) (Receipt, error)
	// Verify validates an async callback, returning the trusted order number and external transaction id.
	Verify(ctx context.Context, raw []byte) (Callback, error)
}

// Order is a collection order initiated by the panel.
type Order struct {
	OrderNo     string // order number generated by the panel
	UserID      int64  // target user
	AmountCents int64  // amount (cents), 0 for card-key redemption
	Product     string // product description, e.g. a "50GB traffic card key"
	CreatedAt   time.Time
}

// Receipt is the Provider's answer to an order.
type Receipt struct {
	Provider   string // card / epusdt / wechat / alipay
	PayURL     string // payment page URL, empty for card keys
	ExternalID string // external order number (epusdt etc.), empty for card keys
	ExpiresAt  time.Time
}

// Callback is the verdict after signature verification.
type Callback struct {
	OrderNo     string
	ExternalID  string // transaction id / txid
	AmountCents int64
	PaidAt      time.Time
	Raw         []byte // raw callback, kept in the ledger table for reference
}

var (
	regMu    sync.RWMutex
	registry = map[string]Provider{}
)

// Register registers a Provider; a later registration under the same name overrides the earlier one (payments/ plugins self-register in init()).
func Register(p Provider) {
	regMu.Lock()
	defer regMu.Unlock()
	registry[p.Name()] = p
}

// Get fetches a Provider by name, erroring when unregistered (the server only lets calls through for enabled channels).
func Get(name string) (Provider, error) {
	regMu.RLock()
	defer regMu.RUnlock()
	p, ok := registry[name]
	if !ok {
		return nil, fmt.Errorf("payment provider %q not registered", name)
	}
	return p, nil
}

// Names returns registered channel names in lexicographic order (for diagnostics and config validation).
func Names() []string {
	regMu.RLock()
	defer regMu.RUnlock()
	out := make([]string, 0, len(registry))
	for name := range registry {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

// ChannelState describes the availability of a registered collection channel (used by the SHOP-1 panel channel picker).
type ChannelState struct {
	Name    string `json:"name"`
	Enabled bool   `json:"enabled"`
}

// Channels returns all registered channels with their availability in name order: placeholder
// channels (NewDisabled, credentials not in place) are reported unavailable, real implementations available.
// The panel renders the channel picker from registration state; placeholder channels are greyed out
// on the front end with a "not enabled" hint.
func Channels() []ChannelState {
	regMu.RLock()
	defer regMu.RUnlock()
	out := make([]ChannelState, 0, len(registry))
	for name, p := range registry {
		_, placeholder := p.(disabled)
		out = append(out, ChannelState{Name: name, Enabled: !placeholder})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}
